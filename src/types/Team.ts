/**
 * Фракция сущности: определяет, кто кого может атаковать и кто союзник.
 * - player — игрок и его будущие союзники;
 * - enemy — враждебные сущности;
 * - neutral — небоевые/тренировочные сущности (манекены): атакуются всеми,
 *   но сами ни в чьей команде.
 */
export type Team = 'player' | 'enemy' | 'neutral';

/**
 * Проверяет, враждебны ли две фракции друг другу.
 * Neutral не воюет ни с кем, но является допустимой целью для всех.
 * @param a - Первая фракция
 * @param b - Вторая фракция
 */
export function areHostile(a: Team, b: Team): boolean {
	return a !== b;
}
